MARKER = "P3-HANJIAYANG"


def render(block, style, indent):
    '“”把注释块渲染成带缩进的文本行。“”'
    out = []
    if style == "doc":
        out.append(indent + "/**")
        for line in block:
            out.append((indent + " * " + line).rstrip() if line else indent + " *")
        out.append(indent + " */")
    else:
        for line in block:
            out.append((indent + "// " + line).rstrip() if line else indent + "//")
    return out


def annotate(path, blocks):
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().split("\n")

    if any(MARKER in ln for ln in lines):
        return None, 0

    # 校验行号合法且目标行非空
    for lineno, _, _ in blocks:
        if lineno < 1 or lineno > len(lines):
            raise SystemExit("%s: 插入行号越界 %d" % (path, lineno))
        if not lines[lineno - 1].strip():
            raise SystemExit("%s: 第 %d 行为空行，不适合作为插入锚点" % (path, lineno))

    by_line = {}
    for lineno, style, block in blocks:
        if lineno in by_line:
            raise SystemExit("%s: 第 %d 行重复定义注释" % (path, lineno))
        by_line[lineno] = (style, block)

    out = []
    added = 0
    for idx, line in enumerate(lines, start=1):
        if idx in by_line:
            style, block = by_line[idx]
            indent = line[: len(line) - len(line.lstrip())]
            rendered = render(block, style, indent)
            out.extend(rendered)
            added += len(rendered)
        out.append(line)

    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    return added, len(blocks)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..")))
    args = parser.parse_args()

    total_lines = 0
    total_blocks = 0
    for rel, blocks in FILES:
        path = os.path.join(args.root, rel)
        added, nblocks = annotate(path, blocks)
        if added is None:
            print("%-52s 已注入，跳过" % rel)
            continue
        total_lines += added
        total_blocks += nblocks
        print("%-52s %3d 处 / 新增 %3d 行注释" % (rel, nblocks, added))
    print("-" * 78)
    print("合计：%d 处注释块，新增 %d 行注释" % (total_blocks, total_lines))


